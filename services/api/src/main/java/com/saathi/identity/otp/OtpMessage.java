package com.saathi.identity.otp;

import com.saathi.identity.domain.OtpPurpose;
import java.time.Instant;

/**
 * What a delivery channel needs to know: which address to send to, the six digits, and when they
 * stop being worth sending.
 *
 * <p>The phone number is in it because an SMS gateway cannot deliver to a hash. Nothing else in
 * the platform keys on it — no table column, no log line, no error body (§10, §12.8) — and the
 * only code that ever sees it is this port and its providers.
 *
 * @param to        normalised E.164 number, never the value the client typed
 * @param code      six digits, generated by the service and never persisted
 * @param expiresAt when verifying it stops being possible; a message that says "valid for five
 *                  minutes" is a claim about this instant
 * @param purpose   why the code exists, so a provider can vary wording; §12.8's actual binding is
 *                  enforced by the challenge row, not by the text
 */
public record OtpMessage(String to, String code, Instant expiresAt, OtpPurpose purpose) {
}
